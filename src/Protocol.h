#pragma once
// Протокол MiniCraft: номера пакетов и общие структуры клиента и сервера.
#include <cstdint>

constexpr uint16_t PROTOCOL_VERSION = 6; // 3: исправлен порядок чтения координат; 6: рамки для предметов (C_PAINTING 2/3)
constexpr int DEFAULT_PORT = 25565;

enum PacketType : uint16_t {
    // ---- Клиент -> сервер
    C_LOGIN = 1,          // u16 версия, str имя
    C_CHUNK_REQ = 2,      // i32 cx, i32 cz — прислать правки чанка
    C_SET_BLOCK = 3,      // i32 x, u8 y, i32 z, u8 блок, u8 мета, u8 (1 — только мета)
    C_PLAYER = 4,         // PlayerNet + u32 транспорт, f32 вперёд, f32 вбок
    C_CHAT = 5,           // str строка (с «/» — команда серверу)
    C_DIG = 6,            // i32 x, u8 y, i32 z, инструмент (u16 id, u16 damage, 4 x u16 чары), u8 творческий
    C_ATTACK = 7,         // u32 моб, u16 урон, f32 отдача, u8 огонь (тиков/20), u8 добыча
    C_ATTACK_PLAYER = 8,  // u32 игрок, u16 урон, f32 отдача
    C_INTERACT = 9,       // u32 моб, предмет в руке (ItemNet)
    C_SHOOT = 10,         // f32x3 откуда, f32x3 куда, f32 скорость, u8 крит, f32 урон, u8 отдача, u8 огонь, u8 подбор
    C_THROW = 11,         // f32x3 откуда, f32x3 куда, u16 предмет, u16 damage
    C_DROP = 12,          // f32x3 глаза, f32x3 взгляд, ItemNet
    C_TNT = 13,           // i32 x, u8 y, i32 z — поджечь динамит
    C_VEHICLE_PLACE = 14, // u8 вид, f32x3 позиция, f32 yaw
    C_VEHICLE_HIT = 15,   // u32 транспорт, u8 творческий
    C_VEHICLE_USE = 16,   // u32 транспорт, ItemNet в руке
    C_DISMOUNT = 17,      // слезть (транспорт или свинья)
    C_OPEN = 18,          // u8 вид (0 блок, 1 вагонетка), i32 x, u8 y, i32 z | u32 транспорт
    C_CONTAINER = 19,     // u8 вид, ключ (как в C_OPEN), u8 n, n x ItemNet — новое содержимое
    C_CLOSE = 20,         // закрыл окно
    C_SIGN = 21,          // i32 x, u8 y, i32 z, 4 x str
    C_DIM = 22,           // i8 измерение — перешёл через портал / возродился
    C_SAVE = 23,          // blob — сохранение игрока
    C_SLEEP = 24,         // u8 спит ли
    C_PAINTING = 26,      // u8 0: i32 x, u8 y, i32 z, i8 fx, i8 fz — повесить на грань; u8 1: u32 картина — сломать;
                          // u8 2: как 0, но рамка для предмета; u8 3: u32 рамка, ItemNet в руке — вставить/повернуть
    C_KEEPALIVE = 25,     // u32 — ответ на S_KEEPALIVE (сервер меряет пинг)

    // ---- Сервер -> клиент
    S_LOGIN_OK = 100,   // u32 id, u32 сид, u8 генератор, i64 время, u8 дождь, u8 гроза, f32x3 появление, u8 режим, u8 сложность, str приветствие, u8 pvp, u8 оператор (читы)
    S_KICK = 101,       // str причина
    S_CHUNK = 102,      // i32 cx, i32 cz, u32 n, n x (u16 индекс, u16 блок|мета<<8), u16 табличек, (i32 x,u8 y,i32 z, 4 x str)
    S_BLOCKS = 103,     // u32 n, n x (i32 x, u8 y, i32 z, u8 блок, u8 мета)
    S_PLAYER_ADD = 104, // u32 id, str имя
    S_PLAYER_DEL = 105, // u32 id
    S_PLAYER = 106,     // u32 id + PlayerNet
    S_CHAT = 107,       // str
    S_TIME = 108,       // i64 время, u8 дождь, u8 гроза
    S_ENTITIES = 109,   // снимок сущностей вокруг игрока (см. Server.cpp writeEntities)
    S_DAMAGE = 110,     // u16 урон, i8 источник, f32x3 толчок, u16 огонь, u16 яд, u8 сквозь броню
    S_SOUND = 111,      // str имя, f32x3 где (NaN — везде), f32 громкость, f32 высота
    S_NOTE = 112,       // i32 x, u8 y, i32 z — сыграл нотный блок
    S_DIGFX = 113,      // i32 x, u8 y, i32 z, u8 блок, u8 мета — звук и осколки ломания
    S_EXPLODE = 114,    // f32x3, f32 сила — частицы взрыва
    S_GIVE = 115,       // ItemNet — подобрал предмет
    S_XP = 116,         // u16 опыт
    S_KILL = 117,       // u8 вид моба — убил (достижения)
    S_ACHIEVE = 118,    // u8 бит достижения
    S_TELEPORT = 119,   // f32x3
    S_POTION = 120,     // u8 эффект, u8 сила, u16 длительность (лечение — сразу)
    S_USE_RESULT = 121, // u8 сколько потратить, ItemNet замена, u8 сел верхом, u32 на ком/чём
    S_CONTAINER = 122,  // u8 вид, ключ, u8 тип, u8 n, n x ItemNet, i16 горение, i16 горение макс, i16 готовка
    S_SIGN = 123,       // i32 x, u8 y, i32 z, 4 x str
    S_PLAYERDATA = 124, // blob — сохранённое состояние игрока
    S_KEEPALIVE = 125,  // u32 — клиент сразу отвечает C_KEEPALIVE; молчит 30 с — отключаем
    S_PLAYER_LIST = 126, // u16 n, n x (u32 id, str имя, u16 пинг мс, i8 измерение) — список по TAB
    S_LIGHTNING = 127,   // f32x3 — удар молнии (вспышка и гром у клиентов; урон и огонь уже посчитал сервер)
};

// Состояние игрока в сети: позиция, взгляд, флаги позы, предмет в руке, броня, измерение
struct PlayerNet {
    float x = 0, y = 0, z = 0, yaw = 0, pitch = 0;
    uint8_t flags = 0;   // 1 на земле, 2 присел, 4 взмах, 8 мёртв, 16 творческий, 32 больно, 64 горит, 128 спит
    uint16_t held = 0, heldDamage = 0;
    uint16_t armor[4] = {};
    int8_t dim = 0;
};
